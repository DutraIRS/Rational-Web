"""Alembic migrations driven by the app's :class:`~rational.backend.database.Database`.

No ``alembic.ini`` is needed: the migration environment reads the engine URL and the model metadata
from the ``Database`` you pass to ``App(database=...)``, and migrations always run on their own
short-lived engine so they never share connections with the running app.

    python -m rational db init app.py          # create ./migrations
    python -m rational db revision app.py -m "add users" --autogenerate
    python -m rational db upgrade app.py       # to head (or a revision id)
    python -m rational db downgrade app.py -1
    python -m rational db current app.py
    python -m rational db history app.py
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

try:
    from alembic import command
    from alembic.config import Config
except ImportError as exc:  # pragma: no cover
    raise ImportError("migrations need Alembic: pip install 'rational[migrations]'") from exc

if TYPE_CHECKING:
    from .database import Database

ENV_PY = '''\
"""Alembic environment generated by ``rational db init``; it reads the engine and metadata from your app."""

import asyncio

from alembic import context
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy.pool import NullPool

db = context.config.attributes["rational_db"]


def run_migrations(connection):
    context.configure(
        connection=connection,
        target_metadata=db.metadata,
        compare_type=True,
        render_as_batch=connection.dialect.name == "sqlite",
    )
    with context.begin_transaction():
        context.run_migrations()


async def main():
    engine = create_async_engine(db.url, poolclass=NullPool)
    async with engine.connect() as connection:
        await connection.run_sync(run_migrations)
        await connection.commit()
    await engine.dispose()


if context.is_offline_mode():
    raise SystemExit("offline migrations are not supported; run against a database")
asyncio.run(main())
'''

SCRIPT_MAKO = '''\
"""${message}

Revision ID: ${up_revision}
Revises: ${down_revision | comma,n}
Create Date: ${create_date}
"""

from alembic import op
import sqlalchemy as sa
${imports if imports else ""}

revision = ${repr(up_revision)}
down_revision = ${repr(down_revision)}
branch_labels = ${repr(branch_labels)}
depends_on = ${repr(depends_on)}


def upgrade() -> None:
    ${upgrades if upgrades else "pass"}


def downgrade() -> None:
    ${downgrades if downgrades else "pass"}
'''


class MigrationError(Exception):
    pass


def _config(db: Database, directory: str) -> Config:
    path = Path(directory)
    if not (path / "env.py").exists():
        raise MigrationError(f"{directory!r} is not a migrations folder; run `rational db init` first")
    config = Config()
    config.set_main_option("script_location", str(path.resolve()))
    config.attributes["rational_db"] = db
    return config


def init(directory: str = "migrations") -> Path:
    """Create the migrations folder (``env.py``, ``script.py.mako`` and ``versions/``)."""
    path = Path(directory)
    if (path / "env.py").exists():
        raise MigrationError(f"{directory!r} already contains a migration environment")
    (path / "versions").mkdir(parents=True, exist_ok=True)
    (path / "env.py").write_text(ENV_PY, encoding="utf-8")
    (path / "script.py.mako").write_text(SCRIPT_MAKO, encoding="utf-8")
    return path


def revision(db: Database, directory: str, message: str, autogenerate: bool = False) -> None:
    command.revision(_config(db, directory), message=message, autogenerate=autogenerate)


def upgrade(db: Database, directory: str = "migrations", target: str = "head") -> None:
    command.upgrade(_config(db, directory), target)


def downgrade(db: Database, directory: str = "migrations", target: str = "-1") -> None:
    command.downgrade(_config(db, directory), target)


def current(db: Database, directory: str = "migrations") -> None:
    command.current(_config(db, directory), verbose=True)


def history(db: Database, directory: str = "migrations") -> None:
    command.history(_config(db, directory))
